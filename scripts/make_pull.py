"""Write the pull-board (read_board, checked every turn) configs for the main tables, one per environment and model
group, from the original settings: each setting is copied unchanged apart from `pull_board = "check"` and its name.

  python3 scripts/make_pull.py
"""

import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = {  # model group: (models, backend, workers)
    "cc": ([("anthropic/claude-opus-5.5", None), ("anthropic/claude-sonnet-5.5", None), ("anthropic/claude-fable-5.2", None)], "claude-code", 10),
    "or": ([("openai/gpt-6.2-sol", "azure"), ("openai/gpt-6.2-astra", "azure"), ("moonshotai/kimi-k3.1-pro", "deepinfra/bf16"),
            ("deepseek/deepseek-v4.1-flash-1017", "coreweave/fp8")], None, 30),
    "neon": ([("google/gemini-4-neon", "google-ai-studio")], None, 30),
}
# environment: (config the top-level settings come from, [(config holding the setting, setting name)])
ENVS = {
    "ids": ("boards-kimi", [("boards-kimi", "history-real-lj3-s0-question")]),
    "registry": ("rt-sol-registry", [("rt-sol-registry", n) for n in
                 ("registry-empty", "registry-precedent", "registry-pull-operator-alone", "registry-pull-permit-live-peer-bundle")]),
    "storage": ("rt-astra-storage", [("rt-astra-storage", n) for n in
                ("storage-empty", "storage-precedent", "storage-pull-operator-alone", "storage-pull-permit-peer-self")]
                + [("fill-storage-or", n) for n in ("storage-inbox-permit-peer-self", "storage-metrics-note-permit-peer-self")]),
    "review": ("review-neon", [("review-neon", n) for n in ("review-no-list", "review-list-silent", "review-list-precedent")]),
}


def load(name):
    return tomllib.load(open(ROOT / "configs" / f"{name}.toml", "rb"))


def value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k} = {value(x)}" for k, x in v.items()) + "}"
    return "[" + ", ".join(value(x) for x in v) + "]"


def main():
    for env, (base, settings) in ENVS.items():
        top = {k: v for k, v in load(base).items() if k not in ("models", "variants", "backend", "workers")}
        variants = []
        for cfg, name in settings:
            v = dict(next(x for x in load(cfg)["variants"] if x["name"] == name))
            v["name"] = (name if "pull" in name else name.replace(f"{env}-", f"{env}-pull-", 1) if name.startswith(env) else f"pull-{name}") + "-check"
            v["pull_board"] = "check"
            variants.append(v)
        for group, (models, backend, workers) in GROUPS.items():
            out = [f"# Main tables through read_board, checked every turn: {env}, {group} models. Generated by make_pull.py from",
                   f"# {', '.join(sorted({c for c, _ in settings}))}; each setting unchanged apart from pull_board = \"check\"."]
            if backend:
                out.append(f'backend = "{backend}"')
            out += [f"{k} = {value(v)}" for k, v in top.items()] + [f"workers = {workers}"]
            for m, p in models:
                out += ["", "[[models]]", f'model = "{m}"'] + ([f'provider = "{p}"'] if p else [])
            for v in variants:
                v = dict(v, name=v["name"] + ("-claude-code" if backend else ""))
                out += ["", "[[variants]]"] + [f"{k} = {value(x)}" for k, x in v.items()]
            path = ROOT / "configs" / f"pull-{env}-{group}.toml"
            path.write_text("\n".join(out) + "\n")
            print(path.name, len(models), "models x", len(variants), "settings")


if __name__ == "__main__":
    main()
